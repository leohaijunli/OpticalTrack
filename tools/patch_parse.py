parse_fn = (
    "fn parse_samples_object(chunk: &str) -> Vec<Sample> {\n"
    "    let start = match chunk.find(\"" + Q + "samples" + Q + "\") {\n"
    "        Some(i) => i,\n"
    "        None => return Vec::new(),\n"
    "    };\n"
    "    let lb = match chunk[start..].find('[') {\n"
    "        Some(i) => start + i,\n"
    "        None => return Vec::new(),\n"
    "    };\n"
    "    let bytes = chunk.as_bytes();\n"
    "    let mut depth = 0usize;\n"
    "    let mut rb = chunk.len();\n"
    "    for (i, &c) in bytes.iter().enumerate().skip(lb) {\n"
    "        if c == b'[' {\n"
    "            depth += 1;\n"
    "        } else if c == b']' {\n"
    "            depth -= 1;\n"
    "            if depth == 0 {\n"
    "                rb = i;\n"
    "                break;\n"
    "            }\n"
    "        }\n"
    "    }\n"
    "    let arr = match chunk.get(lb + 1..rb) {\n"
    "        Some(a) => a,\n"
    "        None => return Vec::new(),\n"
    "    };\n"
    "    let mut out = Vec::new();\n"
    "    for obj in arr.split('{').skip(1) {\n"
    "        let num = |key: &str| -> f64 {\n"
    "            after_key(obj, key)\n"
    "                .and_then(|r| {\n"
    "                    r.trim_start()\n"
    "                        .split(|c: char| c == ',' || c == '}')\n"
    "                        .next()\n"
    "                })\n"
    "                .and_then(|t| t.trim().parse::<f64>().ok())\n"
    "                .unwrap_or(0.0)\n"
    "        };\n"
    "        let arrn = |key: &str, out_v: &mut [f64]| {\n"
    "            if let Some(seg) = after_key(obj, key) {\n"
    "                if let Some(l) = seg.find('[') {\n"
    "                    if let Some(r) = seg[l..].find(']') {\n"
    "                        if let Some(inner) = seg.get(l + 1..l + r) {\n"
    "                            for (j2, part) in inner.split(',').enumerate().take(out_v.len()) {\n"
    "                                out_v[j2] = part.trim().parse::<f64>().unwrap_or(0.0);\n"
    "                            }\n"
    "                        }\n"
    "                    }\n"
    "                }\n"
    "            }\n"
    "        };\n"
    "        let mut pv = [0.0f64; 3];\n"
    "        arrn(\"p\", &mut pv);\n"
    "        let mut vv = [0.0f64; 3];\n"
    "        arrn(\"v\", &mut vv);\n"
    "        let mut qv = [0.0f64; 4];\n"
    "        arrn(\"q\", &mut qv);\n"
    "        let mut wv = [0.0f64; 3];\n"
    "        arrn(\"w\", &mut wv);\n"
    "        out.push(Sample {\n"
    "            t: num(\"t\"),\n"
    "            p: v3(pv[0], pv[1], pv[2]),\n"
    "            v: v3(vv[0], vv[1], vv[2]),\n"
    "            q: crate::math::quat(qv[0], qv[1], qv[2], qv[3]),\n"
    "            w: v3(wv[0], wv[1], wv[2]),\n"
    "            on_ground: num(\"on_ground\") > 0.5,\n"
    "        });\n"
    "    }\n"
    "    out\n"
    "}\n"
    "\n"
)

